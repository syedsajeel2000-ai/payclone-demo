/* Notifications inbox. */
import { api } from '../api.js';
import { icon, esc, qs, toast, timeAgo, fmtDateTime } from '../ui.js';
import { refreshBell } from '../layout.js';

const TYPE_ICON = {
  sent: 'send',
  received: 'receive',
  success: 'checkCircle',
  security: 'shieldCheck',
  info: 'info',
  topup: 'topup'
};

export async function renderNotifications(container) {
  container.innerHTML = `
    <div class="page-head">
      <div>
        <h1>Notifications</h1>
        <p class="ph-sub">Payments, requests, wallet top-ups and security events for your account.</p>
      </div>
      <div class="ph-actions">
        <span class="pill" id="unread-pill">${icon('bell', 15)} <strong id="unread-count">0</strong> unread</span>
        <button class="btn btn-outline btn-sm" id="mark-all">${icon('check', 15)} Mark all as read</button>
      </div>
    </div>

    <div class="card card-pad-0 reveal">
      <div id="notif-list"><div class="empty"><span class="spinner" style="border-color:rgba(0,112,224,.25);border-top-color:var(--accent);margin:0 auto"></span></div></div>
    </div>

    <div class="demo-strip-inline mt-16">${icon('info', 15)} Notifications are generated by real demo events on your account — nothing here is pre-filled.</div>
  `;

  const listWrap = qs('#notif-list', container);
  const unreadCount = qs('#unread-count', container);
  const markAllBtn = qs('#mark-all', container);

  async function load() {
    try {
      const data = await api('/api/notifications');
      unreadCount.textContent = String(data.unread);
      refreshBell();

      if (!data.items.length) {
        listWrap.innerHTML = `
          <div class="empty">
            <div class="empty-ico">${icon('bell', 34)}</div>
            <h3>You're all caught up</h3>
            <p>Notifications about payments, top-ups and security events will show up here.</p>
            <button class="btn btn-primary" data-nav="/dashboard">Back to Dashboard</button>
          </div>`;
        listWrap.querySelectorAll('[data-nav]').forEach((el) => {
          el.addEventListener('click', () => { location.hash = el.getAttribute('data-nav'); });
        });
        markAllBtn.disabled = true;
        return;
      }

      markAllBtn.disabled = data.unread === 0;
      listWrap.innerHTML = '<div class="notif-list">' + data.items
        .map(
          (n, i) => `
        <button class="notif-item ${n.read ? '' : 'unread'}" data-notif="${esc(n.id)}" data-link="${esc(n.link || '')}" style="--i:${i}">
          <span class="notif-ico ${esc(n.type || 'info')}">${icon(TYPE_ICON[n.type] || 'info', 19)}</span>
          <span class="notif-body">
            <span class="notif-title">${esc(n.title)}${n.read ? '' : ' <span class="badge badge-info">New</span>'}</span>
            <span class="notif-msg" style="display:block">${esc(n.message)}</span>
            <span class="notif-time" style="display:block" title="${esc(fmtDateTime(n.createdAt))}">${esc(timeAgo(n.createdAt))}</span>
          </span>
          ${n.read ? '' : '<span class="unread-dot"></span>'}
        </button>`
        )
        .join('') + '</div>';

      listWrap.querySelectorAll('[data-notif]').forEach((el) => {
        el.addEventListener('click', async () => {
          const id = el.getAttribute('data-notif');
          const link = el.getAttribute('data-link');
          if (!el.classList.contains('unread')) {
            if (link) location.hash = link;
            return;
          }
          try {
            await api('/api/notifications/read', { method: 'POST', body: { ids: [id] } });
          } catch (e) { /* ignore */ }
          if (link) location.hash = link;
          else await load();
          await load();
        });
      });
    } catch (err) {
      if (err.status !== 401) toast('error', 'Could not load notifications.');
    }
  }

  markAllBtn.addEventListener('click', async () => {
    markAllBtn.disabled = true;
    try {
      await api('/api/notifications/read', { method: 'POST', body: { all: true } });
      toast('success', 'All notifications marked as read.');
      await load();
    } catch (err) {
      toast('error', err.message);
      markAllBtn.disabled = false;
    }
  });

  await load();
}
