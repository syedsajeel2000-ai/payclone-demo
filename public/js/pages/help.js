export async function renderHelp(container) {
  container.innerHTML = `
    <div class="page-head">
      <div>
        <h1>Help &amp; Support</h1>
        <p class="ph-sub">Answers to the most common questions about the PayClone demo platform.</p>
      </div>
      <div class="ph-actions">
        <span class="badge badge-demo">${icon('help', 13)} Demo support center</span>
      </div>
    </div>

    <div class="grid grid-main-side">
      <div class="card">
        <div class="card-head">
          <h2>${icon('help', 18)} Frequently Asked Questions</h2>
        </div>
        <div class="faq-list">
          ${FAQS.map(
            (f, i) => `
            <div class="faq-item" data-faq="${i}">
              <button class="faq-q" type="button" aria-expanded="false">
                <span>${esc(f.q)}</span>
                <span class="fq-ico">${icon('chevronDown', 15)}</span>
              </button>
              <div class="faq-a">
                <div class="faq-a-inner">${f.a.map((p) => '<p>' + p + '</p>').join('')}</div>
              </div>
            </div>`
          ).join('')}
        </div>
      </div>

      <div class="stack gap-16">
        <div class="card">
          <div class="card-head"><h2>${icon('zap', 18)} Quick links</h2></div>
          <div class="stack gap-8">
            <button class="btn btn-outline btn-block" data-nav="/send">${icon('send', 16)} Send demo money</button>
            <button class="btn btn-outline btn-block" data-nav="/wallet">${icon('wallet', 16)} Add demo funds</button>
            <button class="btn btn-outline btn-block" data-nav="/receive">${icon('receive', 16)} Create a payment request</button>
            <button class="btn btn-outline btn-block" data-nav="/transactions">${icon('receipt', 16)} Find a transaction</button>
            <button class="btn btn-outline btn-block" data-nav="/security">${icon('shieldCheck', 16)} Security &amp; 2FA</button>
          </div>
        </div>

        <div class="card" style="background:linear-gradient(150deg,#001c53,#003087);border:0;color:#fff">
          <div class="row gap-8" style="color:#9dc4ff;font-weight:800;font-size:.78rem;letter-spacing:.1em">
            ${icon('info', 15)} ABOUT THIS PLATFORM
          </div>
          <p style="margin-top:10px;font-size:.9rem;color:#c6d9fb;line-height:1.65">
            This is an <strong style="color:#fff">educational demo platform and does not transfer real money</strong>.
            Support is simulated too: there is no ticketing backend connected, so browse the FAQ above — it covers
            every feature of the platform.
          </p>
        </div>

        <div class="card">
          <div class="card-head"><h2>${icon('activity', 18)} Platform status</h2></div>
          <div class="detail-list">
            <div class="detail-row"><span class="dr-key">Wallet API</span><span class="dr-val"><span class="badge badge-success">Operational</span></span></div>
            <div class="detail-row"><span class="dr-key">Payments</span><span class="dr-val"><span class="badge badge-success">Operational</span></span></div>
            <div class="detail-row"><span class="dr-key">Email provider</span><span class="dr-val"><span class="badge badge-pending">Not connected (demo)</span></span></div>
            <div class="detail-row"><span class="dr-key">Authenticator</span><span class="dr-val"><span class="badge badge-pending">Simulated (demo)</span></span></div>
          </div>
        </div>
      </div>
    </div>
  `;

  container.querySelectorAll('[data-nav]').forEach((el) => {
    el.addEventListener('click', () => { location.hash = el.getAttribute('data-nav'); });
  });

  qsa('[data-faq]', container).forEach((item) => {
    const btn = item.querySelector('.faq-q');
    const panel = item.querySelector('.faq-a');
    btn.addEventListener('click', () => {
      const open = item.classList.contains('open');
      /* accordion: close others */
      qsa('[data-faq]', container).forEach((other) => {
        other.classList.remove('open');
        other.querySelector('.faq-a').style.maxHeight = '0px';
        other.querySelector('.faq-q').setAttribute('aria-expanded', 'false');
      });
      if (!open) {
        item.classList.add('open');
        panel.style.maxHeight = panel.scrollHeight + 'px';
        btn.setAttribute('aria-expanded', 'true');
      }
    });
  });
}
